"""
Google Gemini Multimodal Video Intelligence Service (`services/gemini_service.py`).

Responsibilities:
- Uploads video files to the Gemini Files API (`google-genai` SDK) and polls until `ACTIVE`,
  with automatic fallback to timestamped FFmpeg keyframe grid analysis for large uploads (>95 MB).
- Enforces strict Pydantic `response_schema` JSON output for cut segments, transitions,
  speed ramps, energy scores, and timed voiceover narration lines.
- Sanitizes and clamps timestamps against actual `ffprobe` source duration and target edit budget.
- Always deletes temporary cloud files from Gemini Files API in a `finally` block.
"""

from __future__ import annotations

import asyncio
import logging
import os
import re
import time
from pathlib import Path
from typing import Any, Awaitable, Callable, Literal, Optional

from google import genai
from google.genai import types
from pydantic import BaseModel, Field
from tenacity import (
    retry,
    retry_if_exception,
    stop_after_attempt,
    wait_exponential,
)

from services.video_engine import RenderSegmentSpec, VideoEngine, VideoMetadata

logger = logging.getLogger("cineflow.gemini_service")

ProgressCallback = Callable[[int, str], Awaitable[None]]


class GeminiServiceError(RuntimeError):
    """Raised when Gemini multimodal video analysis fails."""


class GeminiCutSegment(BaseModel):
    """Strict schema for a single edit decision generated by Gemini."""

    start: float = Field(
        ...,
        description="Clip start timestamp in the source video in seconds (e.g. 0.0).",
    )
    end: float = Field(
        ...,
        description="Clip end timestamp in the source video in seconds (must be > start).",
    )
    action: Literal["cut", "highlight", "speed_ramp", "intro", "outro"] = Field(
        default="cut",
        description="Editorial role of this kept clip segment.",
    )
    transition: Literal["cut", "fade", "flash"] = Field(
        default="cut",
        description="Visual transition effect applied to this clip.",
    )
    playback_speed: float = Field(
        default=1.0,
        description="Playback speed factor between 0.6 (slow-mo) and 1.6 (fast-paced). Usually 1.0.",
    )
    scene_label: str = Field(
        ...,
        description="Concise 2-5 word label describing what happens visually in this shot.",
    )
    energy_score: int = Field(
        default=7,
        description="Visual excitement/pacing score from 1 (calm) to 10 (peak action).",
    )
    voiceover_script: str = Field(
        default="",
        description=(
            "Spoken narrator line for this segment (~2.3 words per effective second). "
            "Leave empty string only if original video audio should play un-narrated."
        ),
    )


class GeminiTimelineResponse(BaseModel):
    """Top-level structured edit decision list (EDL) returned by Gemini."""

    title: str = Field(..., description="Catchy editorial project title for this cut.")
    summary: str = Field(..., description="1-2 sentence editorial rationale and story arc.")
    narrative_tone: Literal[
        "energetic",
        "cinematic",
        "professional",
        "humorous",
        "dramatic",
        "conversational",
    ] = Field(default="energetic", description="Dominant narrator delivery style.")
    recommended_voice: Literal["troy", "autumn", "diana", "hannah", "austin", "daniel"] = Field(
        default="troy",
        description="Best matching narrator voice persona.",
    )
    segments: list[GeminiCutSegment] = Field(
        ...,
        min_length=1,
        description="Chronological or story-ordered list of video segments to keep and stitch.",
    )


class EditPlanResult(BaseModel):
    """Validated & sanitized timeline plan passed downstream to Groq and FFmpeg."""

    title: str
    summary: str
    narrative_tone: str
    recommended_voice: str
    analysis_mode: str
    model_used: str
    target_duration: float
    segments: list[RenderSegmentSpec]


def _is_retryable_gemini_error(exc: BaseException) -> bool:
    """Retry transient rate-limit (429), overload (503), and connection timeouts."""
    msg = str(exc).lower()
    retry_tokens = ("429", "resource_exhausted", "503", "unavailable", "deadline", "timeout", "500")
    return any(tok in msg for tok in retry_tokens)


def _file_state_name(file_obj: Any) -> str:
    """Normalize `google-genai` File state enum or string representation."""
    state = getattr(file_obj, "state", None)
    if state is None:
        return "ACTIVE"
    name = getattr(state, "name", None)
    if isinstance(name, str):
        return name.upper()
    return str(state).split(".")[-1].upper()


def infer_duration_from_prompt(prompt: str, source_duration: float, requested_max: Optional[float]) -> float:
    """Infer target highlight duration from explicit slider or natural-language prompt (e.g. '30s TikTok')."""
    if requested_max and requested_max > 0:
        return min(source_duration, max(3.0, requested_max))

    match = re.search(r"\b(\d{1,3})\s*(?:s|sec|secs|second|seconds)\b", prompt.lower())
    if match:
        parsed = float(match.group(1))
        if 4.0 <= parsed <= 300.0:
            return min(source_duration, parsed)

    min_match = re.search(r"\b(\d{1,2})\s*(?:m|min|mins|minute|minutes)\b", prompt.lower())
    if min_match:
        parsed_min = float(min_match.group(1)) * 60.0
        return min(source_duration, parsed_min)

    # Smart default: ~60% highlight cut capped at 45s for snappy social edits
    if source_duration <= 12.0:
        return source_duration
    return round(min(45.0, max(10.0, source_duration * 0.62)), 1)


class GeminiVideoService:
    """Multimodal video analyzer and nonlinear edit timeline architect powered by Google Gemini."""

    def __init__(self) -> None:
        self.primary_model = os.getenv("GEMINI_MODEL", "gemini-2.5-flash")
        self.fallback_model = os.getenv("GEMINI_FALLBACK_MODEL", "gemini-2.0-flash")
        self.direct_upload_limit_mb = float(os.getenv("GEMINI_DIRECT_UPLOAD_LIMIT_MB", "95"))

    def is_configured(self) -> bool:
        key = os.getenv("GEMINI_API_KEY", "").strip()
        return bool(key and key != "your_gemini_api_key_here")

    def _get_client(self) -> genai.Client:
        api_key = os.getenv("GEMINI_API_KEY", "").strip()
        if not api_key or api_key == "your_gemini_api_key_here":
            raise GeminiServiceError(
                "GEMINI_API_KEY is missing or unconfigured. Add a valid key to your environment."
            )
        return genai.Client(api_key=api_key)

    async def analyze_and_plan(
        self,
        video_path: Path,
        metadata: VideoMetadata,
        user_prompt: str,
        work_dir: Path,
        video_engine: VideoEngine,
        max_duration: Optional[float] = None,
        progress_callback: Optional[ProgressCallback] = None,
    ) -> EditPlanResult:
        """
        Analyze uploaded video with Gemini and produce a strictly validated JSON edit timeline.
        """
        client = self._get_client()
        target_dur = infer_duration_from_prompt(user_prompt, metadata.duration, max_duration)
        size_mb = metadata.size_bytes / (1024 * 1024)

        system_instruction = self._build_director_prompt(
            metadata=metadata,
            user_prompt=user_prompt,
            target_duration=target_dur,
        )

        uploaded_remote_file: Any = None
        analysis_mode = "direct_video"

        try:
            contents: list[Any]
            if size_mb <= self.direct_upload_limit_mb:
                try:
                    if progress_callback:
                        await progress_callback(
                            14,
                            f"Uploading video ({size_mb:.1f} MB) to Gemini Multimodal Files API...",
                        )
                    uploaded_remote_file = await self._upload_and_wait_active(
                        client=client,
                        video_path=video_path,
                        progress_callback=progress_callback,
                    )
                    contents = [uploaded_remote_file, system_instruction]
                except Exception as upload_exc:
                    logger.warning(
                        "Direct Gemini video upload failed (%s). Falling back to keyframe grid analysis.",
                        upload_exc,
                    )
                    analysis_mode = "keyframe_grid"
                    contents = await self._build_keyframe_contents(
                        video_path=video_path,
                        metadata=metadata,
                        work_dir=work_dir,
                        video_engine=video_engine,
                        instruction=system_instruction,
                        progress_callback=progress_callback,
                    )
            else:
                analysis_mode = "keyframe_grid"
                contents = await self._build_keyframe_contents(
                    video_path=video_path,
                    metadata=metadata,
                    work_dir=work_dir,
                    video_engine=video_engine,
                    instruction=system_instruction,
                    progress_callback=progress_callback,
                )

            if progress_callback:
                await progress_callback(
                    28,
                    f"Gemini ({self.primary_model}) is identifying scene highlights, cuts & voiceover script...",
                )

            raw_timeline, model_used = await self._generate_structured_timeline(
                client=client,
                contents=contents,
            )

            if progress_callback:
                await progress_callback(
                    38,
                    f"Validating {len(raw_timeline.segments)} AI edit cuts against source timestamps...",
                )

            sanitized_segments = self._sanitize_timeline(
                raw_segments=raw_timeline.segments,
                source_duration=metadata.duration,
                target_duration=target_dur,
            )

            return EditPlanResult(
                title=raw_timeline.title.strip() or "AI Highlight Cut",
                summary=raw_timeline.summary.strip() or "Automated highlight reel and voiceover.",
                narrative_tone=raw_timeline.narrative_tone,
                recommended_voice=raw_timeline.recommended_voice,
                analysis_mode=analysis_mode,
                model_used=model_used,
                target_duration=target_dur,
                segments=sanitized_segments,
            )

        finally:
            if uploaded_remote_file is not None:
                remote_name = getattr(uploaded_remote_file, "name", None)
                if remote_name:
                    try:
                        await asyncio.to_thread(client.files.delete, name=remote_name)
                        logger.debug("Deleted temporary Gemini remote file: %s", remote_name)
                    except Exception as cleanup_exc:
                        logger.warning(
                            "Non-fatal: could not delete remote Gemini file %s: %s",
                            remote_name,
                            cleanup_exc,
                        )

    async def _upload_and_wait_active(
        self,
        client: genai.Client,
        video_path: Path,
        progress_callback: Optional[ProgressCallback] = None,
        timeout_sec: float = 180.0,
    ) -> Any:
        """Upload video file via `client.files.upload` and poll until Gemini finishes indexing."""
        ext = video_path.suffix.lower()
        mime_map = {
            ".mp4": "video/mp4",
            ".mov": "video/quicktime",
            ".webm": "video/webm",
            ".mkv": "video/x-matroska",
            ".avi": "video/x-msvideo",
        }
        mime_type = mime_map.get(ext, "video/mp4")

        uploaded = await asyncio.to_thread(
            client.files.upload,
            file=str(video_path),
            config=types.UploadFileConfig(mime_type=mime_type),
        )

        deadline = time.monotonic() + timeout_sec
        poll_idx = 0
        while True:
            state_name = _file_state_name(uploaded)
            if state_name == "ACTIVE":
                return uploaded
            if state_name == "FAILED":
                raise GeminiServiceError("Gemini Files API reported FAILED while indexing video.")
            if time.monotonic() > deadline:
                raise GeminiServiceError(
                    f"Timed out after {timeout_sec:.0f}s waiting for Gemini video indexing."
                )

            poll_idx += 1
            if progress_callback:
                pct = min(26, 16 + poll_idx * 2)
                await progress_callback(pct, "Gemini indexing multimodal video & audio tracks...")

            await asyncio.sleep(2.5)
            uploaded = await asyncio.to_thread(client.files.get, name=uploaded.name)

    async def _build_keyframe_contents(
        self,
        video_path: Path,
        metadata: VideoMetadata,
        work_dir: Path,
        video_engine: VideoEngine,
        instruction: str,
        progress_callback: Optional[ProgressCallback] = None,
    ) -> list[Any]:
        """Extract 16 timestamped keyframes for fast multimodal analysis of large video files."""
        if progress_callback:
            await progress_callback(
                18,
                "Extracting timestamped keyframe strip for multimodal scene analysis...",
            )

        keyframes = await video_engine.extract_keyframes(
            video_path=video_path,
            output_dir=work_dir / "keyframes",
            duration=metadata.duration,
            count=16,
        )

        contents: list[Any] = [
            f"Source video total duration: {metadata.duration:.2f}s ({metadata.width}x{metadata.height}). "
            f"Below are {len(keyframes)} chronological keyframes sampled with exact timestamps:"
        ]
        for ts, frame_path in keyframes:
            img_bytes = frame_path.read_bytes()
            contents.append(f"[Frame Timestamp: {ts:.2f}s]")
            contents.append(types.Part.from_bytes(data=img_bytes, mime_type="image/jpeg"))

        contents.append(instruction)
        return contents

    async def _generate_structured_timeline(
        self,
        client: genai.Client,
        contents: list[Any],
    ) -> tuple[GeminiTimelineResponse, str]:
        """Invoke Gemini with strict JSON `response_schema` and model fallback resilience."""
        models_to_try = [self.primary_model]
        if self.fallback_model and self.fallback_model != self.primary_model:
            models_to_try.append(self.fallback_model)

        last_exc: Optional[Exception] = None
        for model_name in models_to_try:
            try:
                parsed = await self._call_model_with_retry(
                    client=client,
                    model_name=model_name,
                    contents=contents,
                )
                return parsed, model_name
            except Exception as exc:
                last_exc = exc
                logger.warning("Gemini model '%s' failed: %s", model_name, exc)

        raise GeminiServiceError(f"Gemini video analysis failed across configured models: {last_exc}")

    @retry(
        retry=retry_if_exception(_is_retryable_gemini_error),
        wait=wait_exponential(multiplier=1.5, min=2, max=18),
        stop=stop_after_attempt(3),
        reraise=True,
    )
    async def _call_model_with_retry(
        self,
        client: genai.Client,
        model_name: str,
        contents: list[Any],
    ) -> GeminiTimelineResponse:
        config = types.GenerateContentConfig(
            response_mime_type="application/json",
            response_schema=GeminiTimelineResponse,
            temperature=0.25,
        )

        response = await asyncio.to_thread(
            client.models.generate_content,
            model=model_name,
            contents=contents,
            config=config,
        )

        if getattr(response, "parsed", None) is not None:
            parsed_obj = response.parsed
            if isinstance(parsed_obj, GeminiTimelineResponse):
                return parsed_obj
            if isinstance(parsed_obj, dict):
                return GeminiTimelineResponse.model_validate(parsed_obj)

        raw_text = (getattr(response, "text", None) or "").strip()
        if not raw_text:
            raise GeminiServiceError(f"Gemini model '{model_name}' returned an empty response.")

        return GeminiTimelineResponse.model_validate_json(raw_text)

    @staticmethod
    def _build_director_prompt(
        metadata: VideoMetadata,
        user_prompt: str,
        target_duration: float,
    ) -> str:
        min_seg = min(2.0, max(0.8, metadata.duration * 0.2))
        return (
            "You are an award-winning AI Video Editor, Story Producer, and Voiceover Scriptwriter.\n"
            f"SOURCE MEDIA SPECS:\n"
            f"- Exact Total Source Duration: {metadata.duration:.2f} seconds\n"
            f"- Resolution: {metadata.width}x{metadata.height} ({metadata.aspect_ratio_display}) @ {metadata.fps} fps\n"
            f"- Source Audio Present: {'Yes' if metadata.has_audio else 'No (silent footage)'}\n"
            f"- Target Final Edited Duration: ~{target_duration:.1f} seconds (do NOT exceed {min(metadata.duration, target_duration * 1.15):.1f}s)\n\n"
            f"USER EDITING BRIEF:\n\"{user_prompt.strip()}\"\n\n"
            "EDITORIAL & TECHNICAL RULES:\n"
            f"1. Every segment MUST satisfy `0.0 <= start < end <= {metadata.duration:.2f}`.\n"
            f"2. Each kept segment should be at least {min_seg:.1f}s long (ideally 2.5s to 7.0s per cut for dynamic pacing) "
            "unless the entire source video is shorter.\n"
            "3. Segments must NOT overlap (`segment[i].start >= segment[i-1].end` when chronological).\n"
            "4. Choose purposeful transitions: use `cut` for punchy momentum, `fade` for opening/closing or scene shifts, "
            "and `flash` sparingly for high-energy beat drops.\n"
            "5. Keep `playback_speed` between `0.75` and `1.5` (`1.0` for natural motion).\n"
            "6. Write compelling, natural spoken `voiceover_script` lines tailored to each segment's visual content AND duration: "
            "budget roughly 2.2 to 2.5 spoken words per effective second (`(end - start) / playback_speed`). "
            "For example, a 4.0-second clip should have an 8-to-10 word voiceover sentence so the narrator never rushes.\n"
            "7. Select `recommended_voice` from: `troy` (energetic male), `daniel` (cinematic documentary male), "
            "`austin` (warm conversational male), `autumn` (expressive female), `diana` (crisp professional female), "
            "or `hannah` (bright upbeat female).\n"
            "Return strictly valid JSON conforming to the provided schema."
        )

    @staticmethod
    def _sanitize_timeline(
        raw_segments: list[GeminiCutSegment],
        source_duration: float,
        target_duration: float,
    ) -> list[RenderSegmentSpec]:
        """
        Clamp timestamps, eliminate invalid/micro-cuts, enforce target duration budget,
        and build normalized `RenderSegmentSpec` items.
        """
        min_clip_len = 0.45 if source_duration >= 1.2 else max(0.2, source_duration * 0.5)
        max_budget = min(source_duration * 1.25, max(target_duration * 1.22, target_duration + 3.0))

        cleaned: list[RenderSegmentSpec] = []
        accumulated_effective = 0.0

        for raw in raw_segments:
            start = round(max(0.0, min(source_duration - min_clip_len, float(raw.start))), 3)
            end = round(max(0.0, min(source_duration, float(raw.end))), 3)

            if end - start < min_clip_len:
                continue

            speed = round(max(0.5, min(2.0, float(raw.playback_speed or 1.0))), 2)
            eff_dur = (end - start) / speed

            # Respect overall target duration ceiling once we already have >=2 strong cuts
            if len(cleaned) >= 2 and (accumulated_effective + eff_dur) > max_budget:
                remaining_eff = max_budget - accumulated_effective
                if remaining_eff >= 1.5:
                    end = round(min(source_duration, start + remaining_eff * speed), 3)
                    eff_dur = (end - start) / speed
                else:
                    break

            idx = len(cleaned)
            timeline_start = round(accumulated_effective, 3)
            accumulated_effective += eff_dur
            timeline_end = round(accumulated_effective, 3)

            script = (raw.voiceover_script or "").strip()
            cleaned.append(
                RenderSegmentSpec(
                    index=idx,
                    start=start,
                    end=end,
                    action=raw.action,
                    transition=raw.transition,
                    playback_speed=speed,
                    scene_label=(raw.scene_label or f"Clip {idx + 1}").strip()[:60],
                    energy_score=max(1, min(10, int(raw.energy_score or 7))),
                    voiceover_text=script,
                    orpheus_text=script,
                    timeline_start=timeline_start,
                    timeline_end=timeline_end,
                )
            )

        # Fallback safeguard if model produced completely out-of-range timestamps
        if not cleaned:
            fallback_end = round(min(source_duration, max(min_clip_len, target_duration)), 3)
            cleaned.append(
                RenderSegmentSpec(
                    index=0,
                    start=0.0,
                    end=fallback_end,
                    action="highlight",
                    transition="fade",
                    playback_speed=1.0,
                    scene_label="Main Highlight",
                    energy_score=8,
                    voiceover_text="Check out this highlight moment.",
                    orpheus_text="[excited] Check out this highlight moment.",
                    timeline_start=0.0,
                    timeline_end=fallback_end,
                )
            )

        return cleaned
